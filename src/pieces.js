export function getKicks(type, from, to) {
  const key = `${from}>${to}`;
  if (type === 'I') return KICKS_I[key];
  if (type === 'O') return [[0, 0]];
  return KICKS_JLSTZ[key];
}

export function getCells(type, rotation) {
  return PIECES[type].rotations[rotation];
}
